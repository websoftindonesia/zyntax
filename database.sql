create table if not exists public.contact_messages (id bigint generated by default as identity primary key,name text not null,email text not null,topic text not null,message text not null,created_at timestamptz not null default now());
alter table public.contact_messages enable row level security;
create policy "public can submit contact messages" on public.contact_messages for insert to anon with check (true);
grant insert on public.contact_messages to anon;
grant usage,select on sequence public.contact_messages_id_seq to anon;
